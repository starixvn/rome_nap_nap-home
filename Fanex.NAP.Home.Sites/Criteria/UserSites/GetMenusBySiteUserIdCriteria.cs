namespace Fanex.NAP.Home.Sites.Criteria.UserSites
{
    using Fanex.Data.Repository;

    /// <summary>
    /// The criteria are used to get all menus of a site that the user has permissions on.
    /// </summary>
    public class GetMenusBySiteUserIdCriteria : CriteriaBase
    {
        public int UserId { get; set; }

        public int SiteId { get; set; }

        public string Environment { get; set; }

        /// <summary>
        /// Gets the setting key.
        /// </summary>
        /// <returns>The setting key.</returns>
        public override string GetSettingKey()
        {
            return "NAP_Home_GetMenusBySiteUserId";
        }

        /// <summary>
        /// Determines whether this criteria is valid.
        /// </summary>
        /// <returns>Whether this criteria is valid or not.</returns>
        public override bool IsValid()
        {
            return (this.UserId > 0) &&
                   !string.IsNullOrEmpty(this.Environment);
        }
    }
}